#: The generated artifact. `scripts/port_gitleaks.py` writes it; never hand-edit it.
_SUBSET_PATH = Path(__file__).resolve().parent / "patterns" / "gitleaks_subset.json"


@dataclass(frozen=True)
class _GitleaksRule:
    """One ported upstream rule, precompiled at import."""

    rule_id: str
    pattern: re.Pattern[str]
    #: Lowercased upstream keywords. The rule is skipped unless one of them occurs in the text.
    gate: tuple[str, ...]
    #: True when the pattern has exactly one unnamed group, which upstream uses for the secret
    #: itself; the rest of the match is the surrounding delimiter and must survive.
    secret_is_group_one: bool
    #: gitleaks' entropy floor, carried for PROVENANCE and deliberately NOT enforced. See below.
    entropy: float | None


# THE KEYWORD GATE is kept exactly as upstream ships it — a rule runs only if one of its keywords
# occurs somewhere in the (lowercased) text. Two properties of that are worth stating plainly,
# because both were measured rather than assumed:
#
# * It is what makes the corpus SAFE, not merely fast. `sourcegraph-access-token` carries a bare
#   `[a-fA-F0-9]{40}` alternative — that is every git SHA-1 ever printed. Its `sgp_`/`sourcegraph`
#   keywords are the only thing standing between this redactor and `[REDACTED:...]` in place of
#   every commit hash in a coding transcript. An earlier draft here ungated any rule whose keywords
#   were not literally implied by its own pattern (to protect the vendor-name rules below); on the
#   real 426 KB transcript that immediately redacted a genuine commit SHA, so it was reverted. The
#   gate is also a 5.3x speedup (77 ms gated vs 406 ms ungated on that corpus), but correctness is
#   the reason it stays.
# * It has a known FALSE-NEGATIVE direction, stated rather than hidden. EXACTLY TWO of the 120 rules
#   are keyed on the vendor's NAME rather than on anything the token's own shape implies, so a bare
#   token in a transcript that never names the vendor is not reached:
#     - `airtable-personnal-access-token` — `pat<14 alnum>.<64 hex>`, gated on `airtable`;
#     - `facebook-access-token` — `\d{15,16}(\||%)[0-9a-z\-_]{27,40}`, gated on `facebook`.
#   That enumeration is MECHANICAL, not a hand-kept list: `tests/test_redact_golden.py` derives a
#   matching string for every rule from its own parse tree and asserts that exactly these two fail
#   their own keyword gate. (An earlier version of this comment named only Airtable and said "a few",
#   which is how the second one stayed invisible.) Upstream's own regression corpus cannot show the
#   gap — its generated samples embed the identifier — and `tests/test_redact_golden.py` pins that
#   all 85 golden true positives DO carry their own keyword.
#
# And some keywords are too short to gate anything at all: `jwt`'s is `ey`, `vault-service-token`'s
# is `s.` — both near-universal in English prose, so those rules effectively always run. That is
# inherent to upstream's keyword choice, not something to work around.


def _load_gitleaks_subset(path: Path = _SUBSET_PATH) -> tuple[_GitleaksRule, ...]:
    """Load + precompile the ported subset at import time.

    Compiles under `warnings.simplefilter("error")` for the reason spelled out in
    `scripts/port_gitleaks.py`: an unported POSIX class such as `[[:alnum:]]` compiles happily in
    Python with only a `FutureWarning` and then matches something else entirely, which in a
    REDACTOR means a live credential flows to the model with no error anywhere. A hand-edit that
    reintroduces one must fail loudly here rather than degrade silently.

    Deliberately NOT defensive about a missing or malformed artifact either: a packaging accident
    that dropped the file would leave a redactor quietly 120 rules weaker, and a redactor that
    silently gets weaker is the failure this module is built to avoid.
    """
    document = json.loads(path.read_text(encoding="utf-8"))
    rules: list[_GitleaksRule] = []
    # `re.compile` caches by (pattern, flags), and a cache HIT never re-parses — so it never re-emits
    # the `FutureWarning` the strict compile below is here to catch. Without this purge the guard is
    # only as good as whatever happened to run first in the process: an adversarial review primed the
    # cache with the raw Airtable POSIX pattern and then watched a hand-edited artifact carrying that
    # same pattern import CLEANLY, shipping a dead rule. `_rule_from_entry` and
    # `scripts/port_gitleaks.py` both purge for this exact reason; this loader was the odd one out.
    re.purge()
    with warnings.catch_warnings():
        warnings.simplefilter("error")
        for entry in document["rules"]:
            pattern = re.compile(entry["regex"])
            rules.append(
                _GitleaksRule(
                    rule_id=entry["id"],
                    pattern=pattern,
                    gate=tuple(k.lower() for k in entry.get("keywords") or ()),
                    secret_is_group_one=pattern.groups == 1 and not pattern.groupindex,
                    entropy=entry.get("entropy"),
                )
            )
    return tuple(rules)


_TIER2: tuple[_GitleaksRule, ...] = _load_gitleaks_subset()

# ENTROPY: a deliberate divergence from upstream, and the reason is the cost asymmetry.
#
# gitleaks attaches a Shannon-entropy floor to many rules and drops a match that falls below it.
# That is tuned for a SCANNER, where a false positive costs an engineer a few minutes of triage and
# a false negative costs a missed finding in a repo someone else will also scan. Here the roles are
# INVERTED: a false positive costs the literal string `[REDACTED:github-pat]` appearing in text a
# planner reads — which is exactly what this module already says it wants — while a false negative
# ships a live credential into a language model's context. Nothing downstream can undo that.
#
# The floors also earn their keep in upstream's *generic* rules, whose confidence comes from a
# nearby keyword rather than from the token itself. `scripts/port_gitleaks.py` already dropped all
# 101 of those: everything in `_TIER2` is anchored on a distinctive literal shape, so the prefix IS
# the evidence and the floor is redundant confidence bought with false negatives.
#
# So `entropy` is loaded and carried for provenance, and never applied. Measured against upstream's
# own regression corpus (`tests/data/gitleaks_golden.json`): all 85 true positives match either
# way, and dropping the floors redacts 33 additional credential-SHAPED strings that gitleaks
# tolerates — documentation samples and placeholders like `AIzaaaaaaaa…`. Over-redacting those
# costs the planner nothing. `tests/test_redact_golden.py` pins both halves.


def _placeholder(label: str) -> str:
    return f"[REDACTED:{label}]"


def _replace_assignment(match: re.Match[str]) -> str:
    """Keep `key`, the separator, and the quoting; replace only the value."""
    quote = match.group("quote")
    return (
        f"{match.group('key')}{match.group('sep')}{quote}"
        f"{_placeholder(_ASSIGNMENT_LABEL)}{quote}"
    )


def _apply_gitleaks_rule(rule: _GitleaksRule, text: str) -> str:
    """Substitute one ported rule, replacing the secret and keeping its delimiters.

    Most upstream rules wrap the credential in a single group and let the match run one character
    past it, onto the closing quote/backtick/semicolon that proves the token ended. Replacing the
    whole match would eat that delimiter and corrupt the surrounding line, so a single-unnamed-group
    rule substitutes group 1 in place. Everything else (no groups, or several — `jwt-base64` has 34
    named ones, none of which is the token) replaces the whole match, the over-redacting direction.
    """
    replacement = _placeholder(rule.rule_id)

    def _replace(match: re.Match[str]) -> str:
        if not rule.secret_is_group_one or match.group(1) is None:
            return replacement
        whole = match.group(0)
        offset = match.start()
        start, end = match.span(1)
        return whole[: start - offset] + replacement + whole[end - offset :]

    return rule.pattern.sub(_replace, text)


