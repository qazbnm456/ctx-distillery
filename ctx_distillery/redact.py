"""Host-side transcript redaction — runs BEFORE any transcript text becomes LM context.

`CLAUDE.md` invariant (3): sensitive transcript content is redacted in the ingestion layer, not
left to the planner's judgement. `session.run_distillation` calls `redact_transcript` on every
transcript immediately after the adapter's single `ingest()`, and the redacted list is the ONLY one
threaded into `DistillSession` (both the constructor's `read_transcript_chunk` closure and the
`.arun(transcripts=...)` signature binding) — so there is no path left that hands the model raw text.

THREE TIERS, in this order:

1. **The hand-written patterns** (`_TIER1`) — seven shapes this project owns outright.
2. **A vendored, mechanically-ported subset of gitleaks' rules** (`_TIER2`, 120 rules loaded from
   `patterns/gitleaks_subset.json`, generated by `scripts/port_gitleaks.py`; see `VENDOR.md`).
3. **The operator's OWN rules** (`_TIER3`) — a JSON file named by the `CD_REDACTIONS` env var, for
   the credential shapes only the person running this knows about (a corporate token format, an
   internal header). Empty unless set. See "Tier three" below for the schema and the four checks
   every rule must survive at LOAD time.

**TIER THREE IS ADDITIVE ONLY. It can never disable, override or narrow tiers one and two.** That is
a DELIBERATE divergence from the `TS_TOOLSPACE` convention this feature otherwise mirrors, and it is
written down in three places (here, `.env.example`, `README.md`) precisely so nobody "fixes" it back
into symmetry. In toolscout, `TS_TOOLSPACE` REPLACES the built-in catalog and that is safe: the worst
case of a bad toolspace is FEWER TOOLS. Here the worst case of a replaced catalog is a LEAKED
CREDENTIAL. So the operator's file is appended to a floor it cannot lower — there is no `disable`
key, no label-shadowing, and no ordering knob.

**Tier one is not redundant with tier two, and it must stay FIRST.** That is a measured claim, not
a courtesy to the older code. Exactly TWO of the seven are genuinely UNAVAILABLE from gitleaks:

* `bearer_token` is anchored with a LOOKBEHIND (`(?<=authorization:\\s)`). RE2 cannot express
  lookbehind at all, so no gitleaks rule ever will.
* `secret_assignment` substitutes the VALUE ONLY, keeping `api_key = ` visible so a reviewer can
  still see WHAT was set. Every gitleaks rule replaces a token, never a value inside a binding.

And the decisive argument is not about any single pattern: on a real rendered Claude Code transcript,
the operator's own live API key — an `sk-<uuid-shaped>` PRIVATE-PROXY key — was **not** matched by
any of the 120 gitleaks rules, because it is not a known provider format. Tier one's `api_key`
caught it. An anchored corpus of known vendor prefixes is structurally blind to keys minted by
whoever is in front of you.

FIVE of the seven hand-written patterns ARE redundant with a vendored rule today, and they stay
anyway: `private_key`/`private-key`, `aws_access_key_id`/`aws-access-token`, `github_token`/
`github-pat`, `google_api_key`/`gcp-api-key`, and `api_key` against the several `sk-` vendor rules
(though only for the vendors upstream knows — see above). Tier two is REGENERATED from a moving
upstream, so a refresh that renamed or narrowed one of those would reduce coverage with no signal
anywhere; tier one is the floor that survives it. `tests/test_redact_golden.py`'s `_OVERLAP` table
asserts both halves so the loss surfaces as a red test saying "this shape is now tier-one-only".
`google_api_key` is not even fully redundant now — `gcp-api-key` requires a terminator from a fixed
set where this one ends on `\b`, so `AIza<35>]` is tier-one-only.

CORRECTED per an adversarial review: this used to claim `private_key` was "a DOTALL BEGIN/END block
matcher gitleaks has no equivalent for — RE2 scans line-oriented and upstream's private-key rules
match the header, not the body." That is FALSE, and it was verified false. The vendored `private-key`
rule is `(?i)-----BEGIN[ A-Z0-9_-]{0,100}PRIVATE KEY(?: BLOCK)?-----[\\s\\S-]{64,}?KEY(?: BLOCK)?-----`
— `[\\s\\S]` is RE2's own DOTALL idiom, and it matched a full 202-character block at span (0, 202),
body included. `private_key` keeps its place in tier one on the SAME ground as the other four
redundancies (refresh resilience), not on a capability gitleaks lacks. The paragraph above had
already contradicted itself by listing the pair as redundant-today eight lines later.

Cost, measured on the 426 KB rendered transcript: tier one ~32 ms, both tiers ~110 ms; ~135 ms at
512 KB, plus ~6 ms for one tier-three rule. Zero false positives on real transcript content — the
only tier-two hits were credential SHAPES a past session had already pasted in as its own test
fixtures. Dropping the five most expensive gitleaks rules saved 33 ms for five fewer rules, so all
120 ship. Coverage over shaped provider tokens went 4/14 (tier one alone) to 14/14.

HONEST SCOPE: this is pattern-based and BEST-EFFORT, not a claim of complete secret detection. It
catches credential SHAPES; it cannot catch a secret that looks like prose, a novel token format, or
a password the user typed inline. A human should still eyeball a transcript before sharing a plan
widely. Matches are replaced by a LABELLED placeholder (`[REDACTED:api_key]`,
`[REDACTED:github-pat]`) rather than deleted, so the plan can still say "a credential appeared
here" without carrying it.

NO NETWORK, EVER, and no new dependency. Only stdlib `re`/`json`/`os`/`time`. TruffleHog's model
(POST the candidate secret to the vendor's API to see whether it is live) is the exact inversion of
this module's purpose: this runs over the operator's own private history, so shipping a candidate
secret anywhere to grade it would BE the leak. And redaction is on the core path
(`session.run_distillation` calls it unconditionally), so it may never drag in an HTTP stack.
"""

